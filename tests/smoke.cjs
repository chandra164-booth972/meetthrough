const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1100}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.TEST_URL||'http://127.0.0.1:3000');
 await page.getByRole('heading',{name:'Good people know good people.'}).waitFor();
 assert.equal(await page.locator('.card').count(),3);
 await page.getByRole('button',{name:'Save Maya Chen',exact:true}).click();
 await page.getByRole('button',{name:'♡ Saved · 1',exact:true}).click();
 assert.equal(await page.locator('.card').count(),1);
 await page.getByRole('button',{name:'Find my matchmakers',exact:false}).click();
 await page.getByLabel('First name').fill('Jamie');
 await page.getByLabel('Your age').fill('31');
 await page.getByLabel('Based in').selectOption('New York');
 await page.getByLabel('A little about you').fill('A curious designer who loves cooking and long walks.');
 await page.getByLabel('I’m 18 or older.').check();
 await page.getByRole('button',{name:'Continue →'}).click();
 await page.getByLabel('What matters most to you?').fill('Kindness, curiosity, and a shared sense of humor.');
 await page.locator('#profile-form').getByRole('button',{name:'Find my matchmakers →',exact:true}).click();
 assert.equal(await page.locator('.card').count(),6);
 await page.getByRole('link',{name:'Meet Maya →'}).click();
 await page.getByRole('radio').nth(2).check();
 await page.getByRole('button',{name:'Connect with Maya →'}).click();
 await page.getByLabel('I understand that each profile exchange', {exact:false}).check();
 await page.getByRole('button',{name:'Confirm demo booking →'}).click();
 await page.getByRole('heading',{name:'You’re connected with Maya.'}).waitFor();
 await page.getByRole('button',{name:'View my introductions →'}).click();
 assert.match(await page.locator('.intro-card').innerText(),/5 introductions · \$155/);
 await page.getByRole('button',{name:'Request a brief call →'}).click();
 await page.getByLabel('Preferred day').fill('2026-12-20');
 await page.getByRole('button',{name:'Save demo call request →'}).click();
 await page.getByText('Call requested',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Explore sample introductions'}).click();
 await page.getByRole('button',{name:'Approve profile exchange'}).first().click();
 await page.getByRole('button',{name:'Exchange approved ✓'}).waitFor();
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.reload();
 await page.getByText('Call requested',{exact:true}).waitFor();
 await page.goto('http://127.0.0.1:3000/#discover');
 await page.screenshot({path:'/tmp/meetthrough-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'/tmp/meetthrough-mobile.png',fullPage:true});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false,'mobile must not overflow');
 await page.getByRole('button',{name:'Share',exact:false}).first().click();
 await page.getByRole('heading',{name:'Good things are worth sharing.'}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('Passed: discovery, saving, profile, package selection, booking, call request, consent, persistence, mobile layout, and share guidance.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
